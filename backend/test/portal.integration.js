// Teste completo em banco temporário, sem tocar nos registros do triaqui_db.
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const mysql = require('mysql2/promise');
const bcrypt = require('bcrypt');
require('../envConfig').loadEnv(path.join(__dirname,'../.env'));

async function main() {
  const database=`triaqui_test_${Date.now()}_${crypto.randomBytes(3).toString('hex')}`;
  assert.match(database,/^triaqui_test_\d+_[a-f0-9]{6}$/);
  const admin=await mysql.createConnection({host:process.env.TRIAQUI_DB_HOST||'localhost',port:Number(process.env.TRIAQUI_DB_PORT||3306),user:process.env.TRIAQUI_DB_USER||'root',password:process.env.TRIAQUI_DB_PASSWORD,multipleStatements:true});
  let created=false,server,pool,pythonService;
  try {
    pythonService=await require('../servicoPython').startPythonService();
    await admin.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);created=true;
    let sql=fs.readFileSync(path.join(__dirname,'../../database/triaqui.sql'),'utf8');
    sql=sql.slice(0,sql.indexOf('INSERT INTO especialidades'));
    sql=sql.replace(/CREATE DATABASE IF NOT EXISTS triaqui_db[^;]*;/,'').replace('USE triaqui_db;',`USE \`${database}\`;`);
    await admin.query(sql);
    process.env.TRIAQUI_DB_NAME=database;
    pool=require('../db');
    const hash=await bcrypt.hash('TesteSeguro@2026',10);
    for(const [id,perfil] of [[1,'paciente'],[2,'paciente'],[3,'paciente'],[4,'profissional'],[5,'administrativo'],[6,'profissional']]) {
      await pool.query('INSERT INTO usuarios(id,nome,documento,email,telefone,senha_hash,perfil) VALUES (?,?,?,?,?,?,?)',[id,`Teste ${id}`,String(id).padStart(11,'0'),`p${id}@example.test`,'11999999999',hash,perfil]);
    }
    await pool.query("INSERT INTO especialidades(id,nome) VALUES (1,'Especialidade teste')");
    await pool.query("INSERT INTO profissionais(id,usuario_id,registro_profissional) VALUES (1,4,'TESTE-1'),(2,6,'TESTE-2')");
    await pool.query('INSERT INTO profissional_especialidades VALUES (1,1),(2,1)');
    const app=require('../server');
    server=await new Promise(resolve=>{const instance=app.listen(0,'127.0.0.1',()=>resolve(instance));});
    const base=`http://127.0.0.1:${server.address().port}/api/triaqui`;
    const tokens={};
    async function call(method,route,user,body,expected=200) {
      const reply=await fetch(base+route,{method,headers:{'Content-Type':'application/json',...(user?{Authorization:`Bearer ${tokens[user]}`}:{})},...(body?{body:JSON.stringify(body)}:{})});
      const data=await reply.json();assert.equal(reply.status,expected,`${method} ${route}: ${JSON.stringify(data)}`);return data;
    }
    await call('GET','/consultas',null,null,401);
    for(let user=1;user<=6;user++) tokens[user]=(await call('POST','/sessao',null,{documento:String(user).padStart(11,'0'),senha:'TesteSeguro@2026',perfil:user>=4?'staff':'patient'})).token;
    const next=new Date();next.setDate(next.getDate()+7);
    const date=next.toLocaleDateString('en-CA');
    await call('POST','/horarios',4,{profissionalId:1,data:date,horario:'10:00'},201);
    await call('POST','/horarios',4,{profissionalId:1,data:date,horario:'11:00'},201);
    await call('POST','/horarios',6,{profissionalId:1,data:date,horario:'12:00'},403);
    const slot={profissionalId:1,especialidadeId:1,data:date,horario:'10:00'};
    const races=await Promise.all([1,3].map(user=>fetch(base+'/consultas',{method:'POST',headers:{'Content-Type':'application/json',Authorization:`Bearer ${tokens[user]}`},body:JSON.stringify(slot)}).then(async r=>({status:r.status,data:await r.json(),user}))));
    assert.deepEqual(races.map(r=>r.status).sort(),[201,409]);
    const winner=races.find(r=>r.status===201);const booked=winner.data.id;
    const loser=winner.user===1?3:1;
    console.log('OK: autenticação, permissão de agenda e reserva concorrente sem duplicação');
    await call('PATCH',`/consultas/${booked}/status`,loser,{status:'cancelada'},403);
    const triage=await call('POST','/triagem',2,{pacienteId:1,sintomas:['Teste'],descricao:'Dados fictícios para integração'},201);
    const clinicalRows=(await call('GET','/triagens',2)).triagens;
    assert.ok(triage.mensagem.includes(triage.avaliacaoIA.resumo));
    assert.equal(clinicalRows[0].paciente_id,2);assert.equal(clinicalRows[0].status,'pendente');
    await call('GET','/triagens',5,null,403);
    await call('PATCH',`/triagens/${triage.id}`,4,{prioridade:'alta'});
    await call('POST','/fila',loser,{especialidadeId:1},201);
    await call('POST','/fila',2,{especialidadeId:1},201);
    await call('POST','/fila',2,{especialidadeId:1},409);
    await call('PATCH',`/consultas/${booked}/status`,winner.user,{status:'cancelada'});
    let allocated=(await call('GET','/consultas',2)).consultas.find(c=>c.status==='realocada');
    assert.ok(allocated);assert.equal(allocated.paciente_id,2);
    await call('PATCH',`/consultas/${allocated.id}/reagendar`,2,{data:date,horario:'11:00'});
    const rescheduled=(await call('GET','/consultas',2)).consultas.find(c=>c.id===allocated.id);
    assert.match(rescheduled.inicio,/T11:00/);
    const nextAllocated=(await call('GET','/consultas',loser)).consultas.find(c=>c.status==='realocada');
    assert.ok(nextAllocated);
    console.log('OK: triagem privada, confirmação clínica, fila por prioridade, cancelamento e realocação automática');
    console.log('OK: reagendamento persistente e reaproveitamento da vaga antiga');
    const doc=await call('POST','/documentos',1,{tipo:'declaracao',descricao:'Solicitação fictícia'},201);
    await call('PATCH',`/documentos/${doc.id}`,4,{status:'liberado',resposta:'Resposta fictícia da equipe de teste'});
    assert.equal((await call('GET','/documentos',1)).documentos[0].status,'liberado');
    await call('GET','/documentos',5,null,403);
    const notes=(await call('GET','/notificacoes',1)).notificacoes;
    assert.ok(notes.length);
    await call('PATCH',`/notificacoes/${notes[0].id}/ler`,1);
    await call('PATCH',`/notificacoes/${notes[0].id}/ler`,2,null,404);
    await call('PATCH','/perfil',1,{nome:'Nome atualizado de teste',email:'updated@example.test',telefone:'11999999999'});
    assert.equal((await call('GET','/sessao',1)).usuario.nome,'Nome atualizado de teste');
    const registration={tipo:'paciente',nome:'Cadastro de teste',documento:'52998224725',email:'cadastro@example.test',telefone:'11999999999',senha:'TesteSeguro2026',confirmarSenha:'TesteSeguro2026',cep:'01001000',uf:'SP',cidade:'São Paulo',rua:'Praça da Sé',numero:'1'};
    await call('POST','/cadastro',null,registration,201);
    await call('POST','/cadastro',null,registration,409);
    assert.ok((await call('POST','/sessao',null,{documento:registration.documento,senha:registration.senha,perfil:'patient'})).token);
    console.log('OK: requerimentos, notificações privadas, atualização de perfil e cadastro com login');
    const inputIA={sintomas:[],descricao:'consulta de rotina para acompanhamento e renovacao de receita'};
    const predicted=await call('POST','/triagem',2,inputIA,201);
    assert.equal(predicted.avaliacaoIA.estado,'avaliada_ia');
    assert.equal(predicted.avaliacaoIA.linguagem,'python');
    assert.match(predicted.avaliacaoIA.modelo,/^triaqui-nb-python-/);
    const beforeReview=(await call('GET','/triagens',2)).triagens.find(t=>t.id===predicted.id);
    assert.equal(beforeReview.situacao_avaliacao,'avaliada_ia');
    assert.equal(beforeReview.status,'pendente');
    assert.equal(beforeReview.avaliador_id,null);
    assert.equal(beforeReview.prioridade_ia,'baixa');
    await call('POST','/fila',2,{especialidadeId:1},201);
    assert.equal((await call('GET','/fila',2)).fila[0].prioridade,'baixa');
    assert.equal((await call('GET','/fila',2)).fila[0].revisao_pendente_ia,1);
    await call('PATCH',`/triagens/${predicted.id}`,2,{prioridade:'moderada',justificativa:'Teste'},403);
    await call('PATCH',`/triagens/${predicted.id}`,4,{prioridade:'moderada'},422);
    await call('PATCH',`/triagens/${predicted.id}`,4,{prioridade:'moderada',justificativa:'Revisão fictícia feita pelo profissional de teste'});
    const afterReview=(await call('GET','/triagens',2)).triagens.find(t=>t.id===predicted.id);
    assert.equal(afterReview.situacao_avaliacao,'revisada_medico');
    assert.equal(afterReview.prioridade_ia,'baixa');
    assert.equal(afterReview.prioridade,'moderada');
    assert.equal(afterReview.ia_versao,beforeReview.ia_versao);
    assert.equal(afterReview.revisoes.length,1);
    assert.equal(afterReview.revisoes[0].prioridade_anterior,'baixa');
    assert.equal(afterReview.revisoes[0].prioridade_nova,'moderada');
    assert.equal((await call('GET','/fila',2)).fila[0].prioridade,'moderada');
    assert.equal((await call('GET','/fila',2)).fila[0].revisao_pendente_ia,0);
    // A IA também precisa atualizar quem já está aguardando e reordenar a fila.
    const neutral=await call('POST','/triagem',3,{sintomas:['Teste'],descricao:'Exemplo fictício sem classificação'},201);
    await call('PATCH',`/triagens/${neutral.id}`,4,{prioridade:'moderada'});
    await call('POST','/fila',3,{especialidadeId:1},201);
    const promoted=await call('POST','/triagem',2,{descricao:'dor abdominal intensa com vomitos repetidos'},201);
    assert.equal(promoted.avaliacaoIA.prioridade,'alta');
    const provisional=(await call('GET','/triagens',2)).triagens.find(t=>t.id===promoted.id);
    assert.equal(provisional.status,'pendente');
    assert.equal(provisional.avaliador_id,null);
    assert.equal(provisional.revisoes.length,0);
    assert.equal((await call('GET','/fila',4)).fila[0].paciente_id,2);
    assert.equal((await call('GET','/fila',2)).fila[0].prioridade,'alta');
    await call('PATCH',`/triagens/${promoted.id}`,4,{prioridade:'baixa',justificativa:'Revisão fictícia de teste alterou a prioridade provisória'});
    assert.equal((await call('GET','/fila',2)).fila[0].prioridade,'baixa');
    assert.equal((await call('GET','/fila',4)).fila[0].paciente_id,3);
    console.log('OK: IA altera a fila antes da revisão e a alteração médica posterior prevalece');
    process.env.TRIAQUI_AI_ENABLED='false';
    const unavailable=await call('POST','/triagem',3,inputIA,201);
    delete process.env.TRIAQUI_AI_ENABLED;
    assert.equal(unavailable.avaliacaoIA.estado,'falha');
    const pending=(await call('GET','/triagens',3)).triagens.find(t=>t.id===unavailable.id);
    assert.equal(pending.situacao_avaliacao,'pendente');
    assert.equal(pending.prioridade_ia,null);
    assert.equal((await call('GET','/fila',3)).fila[0].prioridade,'moderada');
    console.log('OK: predição de IA persistida, alteração médica justificada, histórico imutável e fallback honesto');
    const [[counts]]=await pool.query('SELECT COUNT(*) total FROM consultas');assert.ok(counts.total>=3);
    console.log('Integração MySQL concluída com dados exclusivamente fictícios.');
  } finally {
    if(server) await new Promise(resolve=>server.close(resolve));
    if(pool) await pool.end();
    if(pythonService?.child)pythonService.child.kill();
    if(created) { await admin.query(`DROP DATABASE \`${database}\``);console.log('Banco temporário de teste removido; banco do usuário preservado.'); }
    await admin.end();
  }
}
main().catch(error=>{console.error(error.message||error.code);process.exitCode=1;});
